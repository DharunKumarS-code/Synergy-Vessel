/* Gemini Location AI details shown on Excel Import rows (AI-generated labelling, reasoning, ambiguity, low confidence;
   nothing accepted automatically), and the removal of the Location Review / Synonyms / Location AI management UI
   (2026-11-23; the backend APIs are unchanged). Mocked API responses only. */
import { render, screen, within } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import App from '../App'
import AiLocationDetails from '../components/AiLocationDetails'
import * as api from '../services/api'
import * as fx from './fixtures'

vi.mock('../services/api', async (orig) => {
  const actual = await orig()
  return {
    ...actual,
    getHealth: vi.fn(), getVessels: vi.fn(), getLocations: vi.fn(), getAllInspections: vi.fn(), getSession: vi.fn(),
    decideLocation: vi.fn(), getAiStatus: vi.fn(),
  }
})

beforeEach(() => {
  vi.clearAllMocks()
  api.getHealth.mockResolvedValue(fx.health)
  api.getVessels.mockResolvedValue(fx.vessels)
  api.getLocations.mockResolvedValue(fx.locations)
  api.getAllInspections.mockResolvedValue({ total: 4, items: fx.inspections.items })
  api.getSession.mockResolvedValue({ authenticated: true, user: fx.adminUser })
})

describe('AI location details', () => {
  it('labels the suggestion as AI-generated by Gemini and shows reasoning, ambiguity and low confidence', () => {
    render(<AiLocationDetails info={{ ai_suggestion: 'CARGO HOLD NO. 3', ai_provider: 'gemini', ai_reason: 'Hold 3 in the text.',
      ai_ambiguous: true, ai_alternatives: ['CARGO HOLD NO. 3', 'Cross deck between # 1&2'], ai_low_confidence: true }} />)
    const box = screen.getByLabelText('AI details')
    expect(box).toHaveTextContent('AI-generated · Gemini · not a decision')
    expect(screen.getByLabelText('AI reasoning')).toHaveTextContent('AI reasoning: Hold 3 in the text.')
    expect(screen.getByLabelText('AI ambiguity')).toHaveTextContent('Ambiguous — AI found several plausible locations: CARGO HOLD NO. 3 · Cross deck between # 1&2')
    expect(screen.getByLabelText('Low AI confidence')).toBeInTheDocument()
    expect(screen.queryAllByRole('button')).toHaveLength(0)                      // information only; no accept action here
  })

  it('shows nothing when the AI made no suggestion and found no alternatives', () => {
    const { container } = render(<AiLocationDetails info={{ ai_suggestion: null, ai_alternatives: [], ai_provider: 'gemini' }} />)
    expect(container).toBeEmptyDOMElement()
  })

  it('omits flags that do not apply', () => {
    render(<AiLocationDetails info={{ ai_suggestion: 'BRIDGE DECK', ai_provider: 'gemini', ai_alternatives: [] }} />)
    expect(screen.queryByLabelText('AI ambiguity')).toBeNull()
    expect(screen.queryByLabelText('Low AI confidence')).toBeNull()
    expect(screen.queryByLabelText('AI reasoning')).toBeNull()
  })
})

const renderAt = (path) => render(
  <MemoryRouter initialEntries={[path]} future={{ v7_startTransition: true, v7_relativeSplatPath: true }}>
    <App />
  </MemoryRouter>,
)

describe('Location Review, Location Synonyms and Location AI management are removed from the UI', () => {
  beforeEach(() => api.getAiStatus.mockResolvedValue({ available: true, provider: 'gemini', model: 'gemini-3.8-flash', simulated: false,
    live: true, review_statuses: ['PENDING_REVIEW'], store: { stored_analyses: 0 } }))

  it('the navigation no longer lists Location Review or Location Synonyms, and every remaining link has a page', async () => {
    renderAt('/settings')
    const nav = await screen.findByRole('navigation', { name: 'Main navigation' })
    await within(nav).findByRole('group', { name: 'Administration menu' })                       // the admin session has loaded
    expect(within(nav).queryByRole('link', { name: /Location Review/i })).toBeNull()
    expect(within(nav).queryByRole('link', { name: /Location Synonyms/i })).toBeNull()
    expect(within(nav).getAllByRole('link').map((l) => l.textContent.trim()))                     // signed in as an administrator
      .toEqual(['Dashboard', 'Compare Photos', 'Reviews', 'Reports', 'Excel Import', 'Administration', 'Settings'])
    expect(document.querySelector('a[href="/location-review"], a[href^="/location-synonyms"]')).toBeNull()
  })

  it.each(['/location-review', '/location-synonyms', '/location-synonyms?synonym=Forward%20section'])(
    'a direct visit to %s shows the Not Found page, with no group decision or synonym controls', async (path) => {
      renderAt(path)
      expect(await screen.findByText('This page does not exist.')).toBeInTheDocument()
      expect(screen.queryByRole('button', { name: /decide|apply|add synonym|delete/i })).toBeNull()
      expect(document.body.textContent).not.toMatch(/Location review groups|Synonym rules|group decision/i)
    })

  it('Settings no longer shows Location AI, while Condition Analysis (Gemini) is still shown', async () => {
    api.getAiStatus.mockResolvedValue({ available: true, provider: 'gemini', model: 'gemini-3.8-flash', simulated: false, live: true,
      review_statuses: ['PENDING_REVIEW'], store: { stored_analyses: 0 } })
    renderAt('/settings')
    const ai = (await screen.findByRole('heading', { name: 'AI Configuration', level: 3 })).closest('section')
    expect(await within(ai).findByText('Gemini')).toBeInTheDocument()
    expect(within(ai).getByText('gemini-3.8-flash')).toBeInTheDocument()
    expect(ai.textContent).not.toMatch(/Location AI/)
    expect(document.body.textContent).not.toMatch(/key_configured|GEMINI_API_KEY|AIza/)
  })
})
